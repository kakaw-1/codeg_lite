#!/usr/bin/env python3
"""Create a small ModelScope Docker Studio package from a GHCR image tag."""
import argparse
import re
import shutil
from pathlib import Path

IMAGE_RE = re.compile(
    r"^ghcr\.io/[a-z0-9][a-z0-9_.-]*/[a-z0-9][a-z0-9_.-]*:"
    r"[a-zA-Z0-9_][a-zA-Z0-9_.-]*$"
)


def generate(image: str, output: Path) -> None:
    if not IMAGE_RE.fullmatch(image):
        raise ValueError("image must be ghcr.io/owner/repository:tag")
    output.mkdir(parents=True, exist_ok=True)
    template = Path(__file__).resolve().parent.parent / "modelscope" / "README.md"
    if not template.is_file():
        raise FileNotFoundError(f"Missing template: {template}")
    (output / "Dockerfile").write_text(
        "# Auto-generated by GitHub Actions. No runtime secrets are embedded.\n"
        f"FROM {image}\n",
        encoding="utf-8",
    )
    shutil.copy2(template, output / "README.md")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--image", required=True, help="published GHCR image with tag")
    parser.add_argument("--output", type=Path, required=True, help="output directory")
    args = parser.parse_args()
    generate(args.image, args.output)


if __name__ == "__main__":
    main()
